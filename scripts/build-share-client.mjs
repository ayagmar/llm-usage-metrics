// Bundles the share report client (src/share-report/client) with esbuild and writes
// src/share-report/client-bundle.generated.ts: the script and style text that the HTML report
// inlines, with the CSP hashes of exactly those bytes. The CLI build (tsup) only bundles the
// generated strings, so run this after every client change and commit the result.
//
// usage: node scripts/build-share-client.mjs [--check]
//   --check  exit 1 when the committed file differs from a fresh build, writing nothing
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const clientDir = path.join(repoRoot, 'src/share-report/client');
const outputPath = path.join(repoRoot, 'src/share-report/client-bundle.generated.ts');

// Any of these inside an inline <script> or <style> would end the element or open a comment.
const forbiddenSequences = ['</script', '</style', '<!--'];

const sharedOptions = {
  bundle: true,
  minify: true,
  write: false,
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'silent',
  absWorkingDir: repoRoot,
};

async function bundleText(options) {
  const result = await build({ ...sharedOptions, ...options });

  if (result.outputFiles.length !== 1) {
    throw new Error(`Expected one esbuild output, got ${result.outputFiles.length}`);
  }

  return result.outputFiles[0].text;
}

function assertInlineSafe(label, text) {
  const lowerText = text.toLowerCase();

  for (const sequence of forbiddenSequences) {
    if (lowerText.includes(sequence)) {
      throw new Error(`The client ${label} contains ${JSON.stringify(sequence)}`);
    }
  }
}

function cspHash(text) {
  return `sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}`;
}

/** Builds the client and returns the content of client-bundle.generated.ts. */
export async function renderShareClientBundle() {
  const script = await bundleText({
    entryPoints: [path.join(clientDir, 'ui/main.ts')],
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    outfile: 'share-client.js',
  });
  const style = await bundleText({
    entryPoints: [path.join(clientDir, 'styles.css')],
    target: 'es2022',
    outfile: 'share-client.css',
  });

  assertInlineSafe('script', script);
  assertInlineSafe('style', style);

  return [
    '// Generated by scripts/build-share-client.mjs from src/share-report/client. Do not edit.',
    '// Run `node scripts/build-share-client.mjs` after changing the client.',
    '',
    `export const SHARE_CLIENT_SCRIPT = ${JSON.stringify(script)};`,
    '',
    `export const SHARE_CLIENT_SCRIPT_HASH = ${JSON.stringify(cspHash(script))};`,
    '',
    `export const SHARE_CLIENT_STYLE = ${JSON.stringify(style)};`,
    '',
    `export const SHARE_CLIENT_STYLE_HASH = ${JSON.stringify(cspHash(style))};`,
    '',
  ].join('\n');
}

async function readCurrent() {
  try {
    return await readFile(outputPath, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') {
      return undefined;
    }
    throw error;
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const content = await renderShareClientBundle();
  const relativePath = path.relative(repoRoot, outputPath);

  if (check) {
    if ((await readCurrent()) !== content) {
      console.error(
        `${relativePath} is stale; run \`node scripts/build-share-client.mjs\` and commit it.`,
      );
      process.exitCode = 1;
    }
    return;
  }

  await writeFile(outputPath, content, 'utf8');
  console.log(`Wrote ${relativePath}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
